#!/usr/bin/env python3
"""Generate src/lang.rs: the built-in subset of the vanilla `en_us` language table (chat formats,
common command feedback, disconnect reasons) used to render translatable text components.

Source: an en_us language file, e.g. PrismarineJS minecraft-data's data/pc/26.1/language.json or
assets/minecraft/lang/en_us.json from a client jar.

Usage (Python 3 standard library only):
  python3 tools/gen_lang.py minecraft-data/data/pc/26.1/language.json src/lang.rs
"""

import json
import sys

PREFIXES = [
    'chat.type.', 'commands.message.display.', 'commands.list.', 'multiplayer.player.joined', 'multiplayer.player.left',
    'multiplayer.disconnect.', 'disconnect.', 'command.unknown.', 'command.context.', 'command.failed', 'command.expected.',
    'commands.help.', 'permissions.requires.', 'gameMode.', 'argument.entity.notfound.', 'argument.player.',
    'commands.op.', 'commands.deop.', 'commands.kick.', 'commands.ban.', 'commands.pardon.', 'commands.whitelist.',
    'commands.time.', 'commands.weather.', 'commands.gamemode.', 'commands.difficulty.', 'commands.seed.',
    'commands.save.', 'commands.reload.', 'commands.stop.', 'commands.kill.', 'commands.gamerule.',
    'commands.teleport.success.', 'commands.give.success.', 'chat.square_brackets', 'chat.disabled.', 'chat.cannotSend',
    'multiplayer.message_not_delivered', 'options.difficulty.', 'difficulty.lock.',
]


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    lang = json.load(open(sys.argv[1]))
    keys = sorted(k for k in lang if any(k == p or k.startswith(p) for p in PREFIXES))

    def esc(s):
        return json.dumps(s, ensure_ascii=False)

    out = ['//! Built-in subset of the vanilla `en_us` language table (chat formats, command feedback,',
           '//! disconnect reasons), generated from Minecraft 26.1 language data so translatable text',
           '//! components render as readable text. Pass `--lang en_us.json` for the full table.',
           '//! Generated by a script; edit the key list there rather than by hand.', '',
           '#[rustfmt::skip]', 'pub static BUILTIN: &[(&str, &str)] = &[']
    out += [f'    ({esc(k)}, {esc(lang[k])}),' for k in keys]
    out += ['];', '']
    open(sys.argv[2], 'w').write('\n'.join(out))


if __name__ == '__main__':
    main()
